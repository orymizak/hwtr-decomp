#include "common.h"

void osInvalICache(void *vaddr, s32 nbytes) {
    asm volatile(
        ".set noreorder\n\t"
        ".set noat\n\t"
        "blez %1, 1f\n\t"
        "nop\n\t"
        "addiu $t3, $zero, 0x4000\n\t"
        "sltu $at, %1, $t3\n\t"
        "beqz $at, 2f\n\t"
        "nop\n\t"
        "addu $t0, %0, $zero\n\t"
        "addu $t1, %0, %1\n\t"
        "sltu $at, $t0, $t1\n\t"
        "beqz $at, 1f\n\t"
        "nop\n\t"
        "addiu $t1, $t1, -0x20\n\t"
        "andi $t2, $t0, 0x1F\n\t"
        "subu $t0, $t0, $t2\n"
        "3:\n\t"
        "cache 0x10, 0x0($t0)\n\t"
        "sltu $at, $t0, $t1\n\t"
        "bnez $at, 3b\n\t"
        "addiu $t0, $t0, 0x20\n"
        "1:\n\t"
        "jr $ra\n\t"
        "nop\n"
        "2:\n\t"
        "lui $t0, 0x8000\n\t"
        "addu $t1, $t0, $t3\n\t"
        "addiu $t1, $t1, -0x20\n"
        "4:\n\t"
        "cache 0x00, 0x0($t0)\n\t"
        "sltu $at, $t0, $t1\n\t"
        "bnez $at, 4b\n\t"
        "addiu $t0, $t0, 0x20\n\t"
        ".set at\n\t"
        ".set reorder"
        : : "r"(vaddr), "r"(nbytes)
        : "t0", "t1", "t2", "t3"
    );
}
